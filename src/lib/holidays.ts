/** 영업일: 월~금이면서 공휴일·대체공휴일이 아닌 날 */
export function isBusinessDay(ymd: string): boolean {
  const dow = toUTCDate(ymd).getUTCDay();
  return dow !== 0 && dow !== 6 && !(ymd in HOLIDAYS);
}
